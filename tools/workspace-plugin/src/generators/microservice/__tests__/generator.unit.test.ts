import { describe, expect, it } from 'vitest';
import { createTreeWithEmptyWorkspace } from '@nx/devkit/testing';
import { readJson, type Tree } from '@nx/devkit';
import { microserviceGenerator } from '../generator';

function seedIcoreWorkspace(tree: Tree): void {
  tree.write(
    'apps/api/package.json',
    JSON.stringify(
      {
        name: 'api',
        version: '0.0.1',
        private: true,
        dependencies: {
          '@icore/auth-client': '*',
          '@icore/notes-client': '*',
          '@icore/shared': '*',
        },
      },
      null,
      2,
    ),
  );

  tree.write(
    'apps/api/src/app/features.module.ts',
    [
      "import { Module } from '@nestjs/common';",
      "import { NotesModule } from './notes/notes.module';",
      "import { PaymentModule } from './payment/payment.module';",
      '',
      '@Module({',
      '  imports: [NotesModule, PaymentModule],',
      '})',
      'export class FeaturesModule {}',
      '',
    ].join('\n'),
  );

  tree.write(
    'apps/api/src/app/gateway-services.ts',
    [
      '/** Microservices the gateway proxies. Generated by create-icore. */',
      'export const GATEWAY_SERVICES = [',
      "  { name: 'auth', prefix: 'AUTH' },",
      "  { name: 'notes', prefix: 'NOTES' },",
      '];',
      '',
    ].join('\n'),
  );

  tree.write(
    'apps/api/.env.example',
    [
      'API_ORIGIN=http://localhost',
      'API_PORT=3001',
      'AUTH_TRANSPORT=tcp',
      'AUTH_HOST=127.0.0.1',
      'AUTH_PORT=4001',
      'NOTES_TRANSPORT=tcp',
      'NOTES_HOST=127.0.0.1',
      'NOTES_PORT=4004',
      '',
    ].join('\n'),
  );

  tree.write(
    'apps/microservices/notes/project.json',
    JSON.stringify(
      {
        name: 'notes',
        targets: {
          serve: {
            options: {
              port: 9232,
            },
          },
        },
      },
      null,
      2,
    ),
  );
}

describe('microserviceGenerator', () => {
  it('scaffolds microservice, client library, and wires BFF via AST', async () => {
    const tree = createTreeWithEmptyWorkspace();
    seedIcoreWorkspace(tree);

    await microserviceGenerator(tree, { name: 'service-one' });

    // 1. Microservice files
    expect(tree.exists('apps/microservices/service-one/project.json')).toBe(true);
    expect(tree.exists('apps/microservices/service-one/src/main.ts')).toBe(true);
    expect(tree.exists('apps/microservices/service-one/src/app/app.module.ts')).toBe(true);
    expect(tree.exists('apps/microservices/service-one/src/app/app.controller.ts')).toBe(true);
    expect(tree.exists('apps/microservices/service-one/src/app/app.service.ts')).toBe(true);
    expect(tree.exists('apps/microservices/service-one/src/app/db.provider.ts')).toBe(false);

    const msProject = readJson<{
      name: string;
      tags: string[];
      targets: { serve: { options: { port: number } } };
    }>(tree, 'apps/microservices/service-one/project.json');
    expect(msProject.name).toBe('service-one');
    expect(msProject.tags).toEqual(['type:microservice', 'scope:service-one']);
    expect(msProject.targets.serve.options.port).toBe(9235);

    const mainTs = tree.read('apps/microservices/service-one/src/main.ts', 'utf-8') ?? '';
    expect(mainTs).toContain("buildTransportMS('SERVICE_ONE')");
    expect(mainTs).toContain("new Logger('ServiceOne-Bootstrap')");

    const msEnv = tree.read('apps/microservices/service-one/.env.example', 'utf-8') ?? '';
    expect(msEnv).toContain('SERVICE_ONE_TRANSPORT=tcp');
    expect(msEnv).toContain('SERVICE_ONE_PORT=4006');

    // 2. Client library files & tsconfig.base.json alias
    expect(tree.exists('libs/service-one-client/project.json')).toBe(true);
    expect(tree.exists('libs/service-one-client/src/lib/service-one-client.module.ts')).toBe(true);
    expect(tree.exists('libs/service-one-client/src/lib/service-one-client.service.ts')).toBe(true);
    expect(tree.exists('libs/service-one-client/src/lib/service-one-client.tokens.ts')).toBe(true);

    const tsconfigBase = readJson<{
      compilerOptions: { paths: Record<string, string[]> };
    }>(tree, 'tsconfig.base.json');
    expect(tsconfigBase.compilerOptions.paths['@icore/service-one-client']).toEqual([
      './libs/service-one-client/src/index.ts',
    ]);

    // 3. Gateway feature module + AST injection in features.module.ts & gateway-services.ts
    expect(tree.exists('apps/api/src/app/service-one/service-one.module.ts')).toBe(true);
    expect(tree.exists('apps/api/src/app/service-one/service-one.controller.ts')).toBe(true);

    const featuresModule = tree.read('apps/api/src/app/features.module.ts', 'utf-8') ?? '';
    expect(featuresModule).toContain(
      "import { ServiceOneModule } from './service-one/service-one.module';",
    );
    expect(featuresModule).toContain('imports: [NotesModule, PaymentModule, ServiceOneModule]');

    const gatewayServices = tree.read('apps/api/src/app/gateway-services.ts', 'utf-8') ?? '';
    expect(gatewayServices).toContain("{ name: 'service-one', prefix: 'SERVICE_ONE' }");

    const apiPkg = readJson<{ dependencies: Record<string, string> }>(
      tree,
      'apps/api/package.json',
    );
    expect(apiPkg.dependencies['@icore/service-one-client']).toBe('*');

    const apiEnvExample = tree.read('apps/api/.env.example', 'utf-8') ?? '';
    expect(apiEnvExample).toContain('SERVICE_ONE_TRANSPORT=tcp');
    expect(apiEnvExample).toContain('SERVICE_ONE_PORT=4006');
  });

  it('auto-increments ports across multiple generated microservices', async () => {
    const tree = createTreeWithEmptyWorkspace();
    seedIcoreWorkspace(tree);

    await microserviceGenerator(tree, { name: 'billing' });
    await microserviceGenerator(tree, { name: 'notifications' });

    const billingEnv = tree.read('apps/microservices/billing/.env.example', 'utf-8') ?? '';
    const notificationsEnv =
      tree.read('apps/microservices/notifications/.env.example', 'utf-8') ?? '';
    expect(billingEnv).toContain('BILLING_PORT=4006');
    expect(notificationsEnv).toContain('NOTIFICATIONS_PORT=4007');

    const billingProj = readJson<{ targets: { serve: { options: { port: number } } } }>(
      tree,
      'apps/microservices/billing/project.json',
    );
    const notificationsProj = readJson<{ targets: { serve: { options: { port: number } } } }>(
      tree,
      'apps/microservices/notifications/project.json',
    );
    expect(billingProj.targets.serve.options.port).toBe(9235);
    expect(notificationsProj.targets.serve.options.port).toBe(9236);
  });

  it('supports --withDb, --withDocker, --transport=redis, and --tags', async () => {
    const tree = createTreeWithEmptyWorkspace();
    seedIcoreWorkspace(tree);
    tree.write('.env', 'DB_PROVIDER=postgres\n');

    await microserviceGenerator(tree, {
      name: 'webhooks',
      transport: 'redis',
      withDb: true,
      withDocker: true,
      tags: 'domain:payments,tier:backend',
    });

    expect(tree.exists('apps/microservices/webhooks/src/app/db.provider.ts')).toBe(true);
    const dbProvider =
      tree.read('apps/microservices/webhooks/src/app/db.provider.ts', 'utf-8') ?? '';
    expect(dbProvider).toContain("import { PostgresDbModule } from '@icore/db-postgres';");

    const msEnv = tree.read('apps/microservices/webhooks/.env.example', 'utf-8') ?? '';
    expect(msEnv).toContain('WEBHOOKS_TRANSPORT=redis');
    expect(msEnv).toContain('\nWEBHOOKS_REDIS_URL=redis://localhost:6379');

    expect(tree.exists('Dockerfile.ms-webhooks')).toBe(true);

    const msProj = readJson<{ tags: string[] }>(tree, 'apps/microservices/webhooks/project.json');
    expect(msProj.tags).toEqual([
      'type:microservice',
      'scope:webhooks',
      'domain:payments',
      'tier:backend',
    ]);
  });

  it('respects --skipBff and leaves apps/api untouched', async () => {
    const tree = createTreeWithEmptyWorkspace();
    seedIcoreWorkspace(tree);

    await microserviceGenerator(tree, { name: 'worker', skipBff: true });

    expect(tree.exists('apps/microservices/worker/project.json')).toBe(true);
    expect(tree.exists('libs/worker-client/project.json')).toBe(false);
    expect(tree.exists('apps/api/src/app/worker/worker.module.ts')).toBe(false);

    const featuresModule = tree.read('apps/api/src/app/features.module.ts', 'utf-8') ?? '';
    expect(featuresModule).not.toContain('WorkerModule');
  });

  it('throws if microservice already exists or uses a reserved name', async () => {
    const tree = createTreeWithEmptyWorkspace();
    seedIcoreWorkspace(tree);

    await expect(microserviceGenerator(tree, { name: 'api' })).rejects.toThrow(/reserved/i);
    await expect(microserviceGenerator(tree, { name: 'notes' })).rejects.toThrow(/already exists/i);
  });
});
