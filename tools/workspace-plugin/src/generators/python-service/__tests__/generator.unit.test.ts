import { describe, expect, it } from 'vitest';
import { createTreeWithEmptyWorkspace } from '@nx/devkit/testing';
import { readJson, type Tree } from '@nx/devkit';
import { pythonServiceGenerator } from '../generator';

function seedIcoreWorkspace(tree: Tree): void {
  tree.write(
    'apps/api/package.json',
    JSON.stringify(
      {
        name: 'api',
        version: '0.0.1',
        private: true,
        dependencies: {
          '@icore/auth-client': '*',
          '@icore/notes-client': '*',
          '@icore/shared': '*',
        },
      },
      null,
      2,
    ),
  );

  tree.write(
    'apps/api/src/app/features.module.ts',
    [
      "import { Module } from '@nestjs/common';",
      "import { NotesModule } from './notes/notes.module';",
      "import { PaymentModule } from './payment/payment.module';",
      '',
      '@Module({',
      '  imports: [NotesModule, PaymentModule],',
      '})',
      'export class FeaturesModule {}',
      '',
    ].join('\n'),
  );

  tree.write(
    'apps/api/src/app/gateway-services.ts',
    [
      '/** Microservices the gateway proxies. Generated by create-icore. */',
      'export const GATEWAY_SERVICES = [',
      "  { name: 'auth', prefix: 'AUTH' },",
      "  { name: 'notes', prefix: 'NOTES' },",
      '];',
      '',
    ].join('\n'),
  );

  tree.write(
    'apps/api/.env.example',
    [
      'API_ORIGIN=http://localhost',
      'API_PORT=3001',
      'AUTH_TRANSPORT=tcp',
      'AUTH_HOST=127.0.0.1',
      'AUTH_PORT=4001',
      'NOTES_TRANSPORT=tcp',
      'NOTES_HOST=127.0.0.1',
      'NOTES_PORT=4004',
      '',
    ].join('\n'),
  );
}

describe('pythonServiceGenerator', () => {
  it('scaffolds default FastAPI microservice, uv workspace root, Axios client lib, and wires BFF via AST', async () => {
    const tree = createTreeWithEmptyWorkspace();
    seedIcoreWorkspace(tree);

    await pythonServiceGenerator(tree, { name: 'ml-inference' });

    // 1. Python microservice files
    expect(tree.exists('apps/microservices/ml-inference/project.json')).toBe(true);
    expect(tree.exists('apps/microservices/ml-inference/pyproject.toml')).toBe(true);
    expect(tree.exists('apps/microservices/ml-inference/Dockerfile')).toBe(true);
    expect(tree.exists('apps/microservices/ml-inference/src/main.py')).toBe(true);
    expect(tree.exists('apps/microservices/ml-inference/tests/test_main.py')).toBe(true);
    expect(tree.exists('apps/microservices/ml-inference/.env.example')).toBe(true);
    expect(tree.exists('apps/microservices/ml-inference/.env')).toBe(true);

    const msProj = readJson<{
      name: string;
      tags: string[];
      targets: Record<string, { executor: string; command?: string }>;
    }>(tree, 'apps/microservices/ml-inference/project.json');
    expect(msProj.name).toBe('ml-inference');
    expect(msProj.tags).toEqual(['type:microservice', 'lang:python', 'scope:ml-inference']);
    expect(msProj.targets['serve']).toBeDefined();
    expect(msProj.targets['lint']).toBeDefined();
    expect(msProj.targets['format']).toBeDefined();
    expect(msProj.targets['test']).toBeDefined();
    expect(msProj.targets['typecheck']).toBeDefined();

    const pyproject = tree.read('apps/microservices/ml-inference/pyproject.toml', 'utf-8') ?? '';
    expect(pyproject).toContain('name = "ml-inference"');
    expect(pyproject).toContain('"fastapi>=0.115.0"');
    expect(pyproject).toContain('"uvicorn[standard]>=0.32.0"');
    expect(pyproject).toContain('[tool.ruff]');
    expect(pyproject).toContain('[tool.mypy]');

    const dockerfile = tree.read('apps/microservices/ml-inference/Dockerfile', 'utf-8') ?? '';
    expect(dockerfile).toContain('ghcr.io/astral-sh/uv:python3.12-bookworm-slim');
    expect(dockerfile).toContain('ML_INFERENCE_PORT=4006');

    // 2. Root pyproject.toml uv workspace
    expect(tree.exists('pyproject.toml')).toBe(true);
    const rootPyproject = tree.read('pyproject.toml', 'utf-8') ?? '';
    expect(rootPyproject).toContain('[tool.uv.workspace]');
    expect(rootPyproject).toContain('"apps/microservices/ml-inference"');

    // 3. Client library files & tsconfig.base.json path alias
    expect(tree.exists('libs/ml-inference-client/project.json')).toBe(true);
    expect(tree.exists('libs/ml-inference-client/src/index.ts')).toBe(true);
    expect(tree.exists('libs/ml-inference-client/src/lib/ml-inference-client.module.ts')).toBe(
      true,
    );
    expect(tree.exists('libs/ml-inference-client/src/lib/ml-inference-client.service.ts')).toBe(
      true,
    );
    expect(tree.exists('libs/ml-inference-client/src/lib/ml-inference-client.tokens.ts')).toBe(
      true,
    );

    const clientService =
      tree.read('libs/ml-inference-client/src/lib/ml-inference-client.service.ts', 'utf-8') ?? '';
    expect(clientService).toContain('import axios, { type AxiosInstance');
    expect(clientService).toContain('ML_INFERENCE_HTTP_OPTIONS');

    const tsconfigBase = readJson<{
      compilerOptions: { paths: Record<string, string[]> };
    }>(tree, 'tsconfig.base.json');
    expect(tsconfigBase.compilerOptions.paths['@icore/ml-inference-client']).toEqual([
      './libs/ml-inference-client/src/index.ts',
    ]);

    // 4. Gateway feature module + AST injection in features.module.ts & gateway-services.ts
    expect(tree.exists('apps/api/src/app/ml-inference/ml-inference.module.ts')).toBe(true);
    expect(tree.exists('apps/api/src/app/ml-inference/ml-inference.controller.ts')).toBe(true);

    const featuresModule = tree.read('apps/api/src/app/features.module.ts', 'utf-8') ?? '';
    expect(featuresModule).toContain(
      "import { MlInferenceModule } from './ml-inference/ml-inference.module';",
    );
    expect(featuresModule).toContain('imports: [NotesModule, PaymentModule, MlInferenceModule]');

    const gatewayServices = tree.read('apps/api/src/app/gateway-services.ts', 'utf-8') ?? '';
    expect(gatewayServices).toContain("{ name: 'ml-inference', prefix: 'ML_INFERENCE' }");

    const apiPkg = readJson<{ dependencies: Record<string, string> }>(
      tree,
      'apps/api/package.json',
    );
    expect(apiPkg.dependencies['@icore/ml-inference-client']).toBe('*');

    const apiEnvExample = tree.read('apps/api/.env.example', 'utf-8') ?? '';
    expect(apiEnvExample).toContain('ML_INFERENCE_TRANSPORT=http');
    expect(apiEnvExample).toContain('ML_INFERENCE_PORT=4006');
    expect(apiEnvExample).toContain('ML_INFERENCE_URL=http://127.0.0.1:4006');
  });

  it('scaffolds gRPC microservice with .proto, proto target, and NestJS ClientGrpc client', async () => {
    const tree = createTreeWithEmptyWorkspace();
    seedIcoreWorkspace(tree);

    await pythonServiceGenerator(tree, {
      name: 'embeddings',
      framework: 'grpc',
      tags: 'tier:ai,team:data',
    });

    expect(tree.exists('apps/microservices/embeddings/protos/embeddings.proto')).toBe(true);
    const protoContent =
      tree.read('apps/microservices/embeddings/protos/embeddings.proto', 'utf-8') ?? '';
    expect(protoContent).toContain('package embeddings;');
    expect(protoContent).toContain('service EmbeddingsService');

    const msProj = readJson<{
      tags: string[];
      targets: Record<string, { executor: string; dependsOn?: string[] }>;
    }>(tree, 'apps/microservices/embeddings/project.json');
    expect(msProj.tags).toEqual([
      'type:microservice',
      'lang:python',
      'scope:embeddings',
      'tier:ai',
      'team:data',
    ]);
    expect(msProj.targets['proto']).toBeDefined();
    expect(msProj.targets['serve'].dependsOn).toEqual(['proto']);
    expect(msProj.targets['test'].dependsOn).toEqual(['proto']);

    const pyproject = tree.read('apps/microservices/embeddings/pyproject.toml', 'utf-8') ?? '';
    expect(pyproject).toContain('"grpcio>=1.68.0"');
    expect(pyproject).toContain('"grpcio-tools>=1.68.0"');

    const clientModule =
      tree.read('libs/embeddings-client/src/lib/embeddings-client.module.ts', 'utf-8') ?? '';
    expect(clientModule).toContain('Transport.GRPC');
    expect(clientModule).toContain("package: 'embeddings'");

    const apiEnv = tree.read('apps/api/.env.example', 'utf-8') ?? '';
    expect(apiEnv).toContain('EMBEDDINGS_TRANSPORT=grpc');
    expect(apiEnv).toContain('EMBEDDINGS_URL=127.0.0.1:4006');
  });

  it('appends multiple members to root pyproject.toml without duplicating', async () => {
    const tree = createTreeWithEmptyWorkspace();
    seedIcoreWorkspace(tree);

    await pythonServiceGenerator(tree, { name: 'svc-alpha' });
    await pythonServiceGenerator(tree, { name: 'svc-beta' });
    await pythonServiceGenerator(tree, { name: 'svc-alpha', skipBff: true }).catch(() => undefined);

    const rootPyproject = tree.read('pyproject.toml', 'utf-8') ?? '';
    expect(rootPyproject).toContain('"apps/microservices/svc-alpha"');
    expect(rootPyproject).toContain('"apps/microservices/svc-beta"');
  });

  it('respects uvWorkspace=false and leaves root pyproject.toml untouched', async () => {
    const tree = createTreeWithEmptyWorkspace();
    seedIcoreWorkspace(tree);

    await pythonServiceGenerator(tree, { name: 'isolated-svc', uvWorkspace: false });

    expect(tree.exists('pyproject.toml')).toBe(false);
    expect(tree.exists('apps/microservices/isolated-svc/project.json')).toBe(true);
  });

  it('respects skipBff=true and leaves apps/api untouched', async () => {
    const tree = createTreeWithEmptyWorkspace();
    seedIcoreWorkspace(tree);

    await pythonServiceGenerator(tree, { name: 'worker-py', skipBff: true });

    expect(tree.exists('apps/microservices/worker-py/project.json')).toBe(true);
    expect(tree.exists('libs/worker-py-client/project.json')).toBe(false);
    expect(tree.exists('apps/api/src/app/worker-py/worker-py.module.ts')).toBe(false);

    const featuresModule = tree.read('apps/api/src/app/features.module.ts', 'utf-8') ?? '';
    expect(featuresModule).not.toContain('WorkerPyModule');
  });

  it('throws on reserved names, duplicate microservices, or invalid names', async () => {
    const tree = createTreeWithEmptyWorkspace();
    seedIcoreWorkspace(tree);

    await expect(pythonServiceGenerator(tree, { name: 'api' })).rejects.toThrow(/reserved/i);
    await expect(pythonServiceGenerator(tree, { name: '123-invalid' })).rejects.toThrow(/invalid/i);

    await pythonServiceGenerator(tree, { name: 'analytics' });
    await expect(pythonServiceGenerator(tree, { name: 'analytics' })).rejects.toThrow(
      /already exists/i,
    );
  });
});
