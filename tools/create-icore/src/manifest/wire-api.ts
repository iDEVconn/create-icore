import { readFile, rename, rm, writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { join } from 'node:path';
import type { CreateIcoreOptions } from '../lib/options.js';
import { MANIFEST } from './index.js';
import { stripJsonKeys } from './wire-provider.js';

const API = 'apps/api';
const APP_MODULE = `${API}/src/app/app.module.ts`;
const SURFACES_MODULE = `${API}/src/app/graphql/api-surfaces.module.ts`;
const SURFACE_RESOLVERS = `${API}/src/app/graphql/api-surface-resolvers.ts`;
const STORAGE_CONTROLLERS = `${API}/src/app/storage/storage.controllers.ts`;
const STORAGE_CONTROLLERS_GRAPHQL = `${API}/src/app/storage/storage.controllers.graphql.ts`;

const PRINT_WIDTH = 100;

/** A feature's GraphQL surface: its Nest module (ApiSurfacesModule) and its resolver (schema). */
interface Surface {
  module: string;
  moduleFrom: string;
  resolver: string;
  resolverFrom: string;
}

const NOTES: Surface = {
  module: 'NotesGraphqlModule',
  moduleFrom: '../notes/graphql/notes-graphql.module',
  resolver: 'NotesResolver',
  resolverFrom: '../notes/graphql/notes.resolver',
};
const PROFILE: Surface = {
  module: 'ProfileGraphqlModule',
  moduleFrom: '../profile/graphql/profile-graphql.module',
  resolver: 'ProfileResolver',
  resolverFrom: '../profile/graphql/profile.resolver',
};
const STORAGE: Surface = {
  module: 'StorageGraphqlModule',
  moduleFrom: '../storage/graphql/storage-graphql.module',
  resolver: 'StorageResolver',
  resolverFrom: '../storage/graphql/storage.resolver',
};

/**
 * Feature surfaces that exist for these options (spec decisions 2 and 11): every per-feature
 * surface needs a session, so auth=none leaves only the health query of ApiGraphqlModule.
 */
function surfacesFor(opts: CreateIcoreOptions): Surface[] {
  if (opts.authProvider === 'none') return [];
  const out: Surface[] = [];
  if (opts.example === 'notes') out.push(NOTES);
  out.push(PROFILE);
  if (opts.upload !== 'none') out.push(STORAGE);
  return out;
}

/** `head[a, b],` on one line when it fits, else one item per line (prettier's output). */
function list(indent: string, head: string, items: string[], tail: string): string {
  const flat = `${indent}${head}[${items.join(', ')}]${tail}`;
  if (flat.length <= PRINT_WIDTH) return flat;
  return `${indent}${head}[\n${items.map((i) => `${indent}  ${i},`).join('\n')}\n${indent}]${tail}`;
}

function surfacesModuleSource(surfaces: Surface[]): string {
  const imports = [
    "import { Module } from '@nestjs/common';",
    "import { ApiGraphqlModule } from './graphql.module';",
    ...surfaces.map((s) => `import { ${s.module} } from '${s.moduleFrom}';`),
  ];
  return (
    imports.join('\n') +
    '\n\n' +
    '/**\n' +
    ' * The GraphQL API: /api/graphql (ApiGraphqlModule, with the public health query) plus the\n' +
    ' * GraphQL surface of every selected feature. Generated by create-icore. Needs a global\n' +
    ' * ThrottlerModule with a `default` throttler (request-level throttle).\n' +
    ' */\n' +
    '@Module({\n' +
    list('  ', 'imports: ', ['ApiGraphqlModule', ...surfaces.map((s) => s.module)], ',') +
    '\n})\n' +
    'export class ApiSurfacesModule {}\n'
  );
}

function surfaceResolversSource(surfaces: Surface[]): string {
  const imports = [
    "import { HealthResolver } from './health.resolver';",
    ...surfaces.map((s) => `import { ${s.resolver} } from '${s.resolverFrom}';`),
  ];
  return (
    imports.join('\n') +
    '\n\n' +
    '/**\n' +
    ' * Resolvers printed into apps/api/schema.gql (`nx run api:graphql-schema`). Kept apart from\n' +
    ' * ApiSurfacesModule so printing the schema never loads Apollo or the microservice clients.\n' +
    ' * Generated by create-icore for the selected features.\n' +
    ' */\n' +
    '// eslint-disable-next-line @typescript-eslint/no-unsafe-function-type\n' +
    list(
      '',
      'export const API_SURFACE_RESOLVERS: Function[] = ',
      ['HealthResolver', ...surfaces.map((s) => s.resolver)],
      ';',
    ) +
    '\n'
  );
}

async function readIfExists(path: string): Promise<string | null> {
  return existsSync(path) ? readFile(path, 'utf8') : null;
}

/**
 * Add ApiSurfacesModule to the gateway's imports (repo app.module.ts or the auth-none overlay,
 * both end their imports with FeaturesModule) and, for api=graphql, drop the REST ProfileModule
 * whose files are not copied.
 */
async function wireAppModule(targetDir: string, opts: CreateIcoreOptions): Promise<void> {
  const path = join(targetDir, APP_MODULE);
  const src = await readIfExists(path);
  if (src === null) return; // partial fixtures
  if (!/\n\s*FeaturesModule,/.test(src) || !/\n\n@Module\(/.test(src)) {
    throw new Error(
      `wireApi: no FeaturesModule anchor in ${APP_MODULE}; cannot add ApiSurfacesModule`,
    );
  }
  // Idempotent: a second run (e.g. a re-applied step) must not wire the module twice.
  if (src.includes("from './graphql/api-surfaces.module';")) return;
  let next = src
    .replace(
      /\n\n@Module\(/,
      "\nimport { ApiSurfacesModule } from './graphql/api-surfaces.module';\n\n@Module(",
    )
    .replace(/\n(\s*)FeaturesModule,/, '\n$1ApiSurfacesModule,\n$1FeaturesModule,');
  // api=graphql with auth: the REST ProfileModule files are not copied, so its import and entry
  // must go; a module that no longer matches is a template change to fix here, not to ship.
  if (opts.api === 'graphql' && opts.authProvider !== 'none') {
    const importRe = /^import \{ ProfileModule \} from '\.\/profile\/profile\.module';\n/m;
    const entryRe = /\n\s*ProfileModule,/;
    if (!importRe.test(next) || !entryRe.test(next)) {
      throw new Error(
        `wireApi: no ProfileModule import/entry in ${APP_MODULE} to remove (api=graphql)`,
      );
    }
    next = next.replace(importRe, '').replace(entryRe, '');
  }
  await writeFile(path, next);
}

/** api=graphql with a StorageResolver: only the upload/download controller stays REST. */
async function wireStorageControllers(targetDir: string, swap: boolean): Promise<void> {
  const variant = join(targetDir, STORAGE_CONTROLLERS_GRAPHQL);
  if (!existsSync(variant)) return;
  if (swap && existsSync(join(targetDir, STORAGE_CONTROLLERS))) {
    await rename(variant, join(targetDir, STORAGE_CONTROLLERS));
  } else {
    await rm(variant, { force: true });
  }
}

/** api=rest: the gateway config goes back to its pre-GraphQL shape. */
async function stripGraphqlServer(targetDir: string): Promise<void> {
  const deps = new Set(Object.keys(MANIFEST.api.graphql.deps));
  await stripJsonKeys(join(targetDir, API, 'package.json'), (k) => deps.has(k));

  const projectPath = join(targetDir, API, 'project.json');
  const project = await readIfExists(projectPath);
  if (project !== null) {
    const next = project.replace(/,\n\s*"graphql-schema": \{[\s\S]*?\n {4}\}(?=\n {2}\})/, '');
    const parsed = JSON.parse(next) as { targets?: Record<string, unknown> };
    if (parsed.targets?.['graphql-schema']) {
      delete parsed.targets['graphql-schema'];
      await writeFile(projectPath, JSON.stringify(parsed, null, 2) + '\n');
    } else {
      await writeFile(projectPath, next);
    }
  }

  const eslintPath = join(targetDir, API, 'eslint.config.mjs');
  const eslint = await readIfExists(eslintPath);
  if (eslint !== null) {
    const next = eslint
      .replace(/^[ \t]*\/\/ @as-integrations\/express5:.*\n/m, '')
      .replace(/^[ \t]*'@as-integrations\/express5',\n/m, '')
      .replace(
        /^([ \t]*)ignoredDependencies: \[\n([\s\S]*?)\n[ \t]*\],/m,
        (whole, indent, body) => {
          const items = (body as string)
            .split('\n')
            .map((l) => l.trim().replace(/,$/, ''))
            .filter(Boolean);
          const flat = `${indent}ignoredDependencies: [${items.join(', ')}],`;
          return flat.length <= PRINT_WIDTH ? flat : whole;
        },
      );
    await writeFile(eslintPath, next);
  }

  const vitestPath = join(targetDir, API, 'vitest.config.mts');
  const vitest = await readIfExists(vitestPath);
  if (vitest !== null) {
    const next = vitest
      .replace(/^import \{ createRequire \} from 'node:module';\n/m, '')
      .replace(/\nconst require = createRequire\(import\.meta\.url\);\n/, '')
      .replace(/\n[ \t]*\/\/ `graphql` ships[\s\S]*?\n[ \t]*alias: \[[^\n]*graphql[^\n]*\],/, '');
    await writeFile(vitestPath, next);
  }
}

/**
 * Repo-wide files that mention GraphQL artefacts: the `.prettierignore` entries of the emitted
 * schema (api != rest) and of the codegen output (graphql with a client), and the `scripts/`
 * include of apps/api/tsconfig.app.json (emit-schema.ts, api != rest).
 */
async function stripGraphqlLeftovers(targetDir: string, opts: CreateIcoreOptions): Promise<void> {
  const ignorePath = join(targetDir, '.prettierignore');
  const ignore = await readIfExists(ignorePath);
  if (ignore !== null) {
    let next = ignore;
    if (opts.api === 'rest') {
      next = next.replace(
        /\n\n# Generated by `nx run api:graphql-schema`[^\n]*\napps\/api\/schema\.gql/,
        '',
      );
    }
    if (opts.api !== 'graphql' || opts.ui === 'none') {
      next = next.replace(
        /\n\n# Generated by `nx run <client>:graphql-codegen`[^\n]*\n\*\*\/src\/gql\/types\.ts/,
        '',
      );
    }
    if (next !== ignore) await writeFile(ignorePath, next);
  }
  if (opts.api === 'rest') {
    const tsconfigPath = join(targetDir, API, 'tsconfig.app.json');
    const tsconfig = await readIfExists(tsconfigPath);
    if (tsconfig !== null) {
      await writeFile(tsconfigPath, tsconfig.replace(/,\s*"scripts\/\*\*\/\*\.ts"/, ''));
    }
  }
}

/**
 * The `--api` axis on the gateway (spec section 9). Runs after writeFeaturesWiring, i.e. after the
 * auth-none overlay and removeUploadStack wrote/edited app.module.ts.
 *  - rest: strip the GraphQL deps, the graphql-schema target and the GraphQL test/lint config.
 *  - graphql/both: generate ApiSurfacesModule + API_SURFACE_RESOLVERS for the selected features,
 *    import ApiSurfacesModule into app.module.ts; graphql also drops the REST ProfileModule and
 *    swaps the storage controller registry (list/signed-url/remove move to StorageResolver).
 */
export async function wireApi(targetDir: string, opts: CreateIcoreOptions): Promise<void> {
  await stripGraphqlLeftovers(targetDir, opts);
  if (opts.api === 'rest') {
    await stripGraphqlServer(targetDir);
    return;
  }
  const surfaces = surfacesFor(opts);
  if (existsSync(join(targetDir, API, 'src/app/graphql'))) {
    await writeFile(join(targetDir, SURFACES_MODULE), surfacesModuleSource(surfaces));
    await writeFile(join(targetDir, SURFACE_RESOLVERS), surfaceResolversSource(surfaces));
  }
  await wireAppModule(targetDir, opts);
  await wireStorageControllers(targetDir, opts.api === 'graphql' && surfaces.includes(STORAGE));
}

const CLIENT = 'apps/client';
/** Query modules with a GraphQL twin (`<name>.gql-api.ts`), same hook names and signatures. */
const CLIENT_SWAPS = ['notes', 'profile'] as const;

/** api=graphql: move each shipped `*.gql-api.ts` twin (and its test) over the REST file. */
async function swapClientQueries(targetDir: string): Promise<void> {
  const queries = join(targetDir, CLIENT, 'src/queries');
  for (const name of CLIENT_SWAPS) {
    const twin = join(queries, `${name}.gql-api.ts`);
    if (!existsSync(twin)) continue; // feature absent: the twin was not copied
    await rename(twin, join(queries, `${name}.ts`));
    const twinTest = join(queries, '__tests__', `${name}.gql-api.unit.test.ts`);
    const test = await readIfExists(twinTest);
    if (test === null) continue;
    await writeFile(
      join(queries, '__tests__', `${name}.unit.test.ts`),
      test.replaceAll(`'../${name}.gql-api'`, `'../${name}'`),
    );
    await rm(twinTest, { force: true });
  }
}

/**
 * Remove `re` from `src` or fail: a template that no longer has the expected GraphQL entry must
 * be fixed here, not shipped half-stripped.
 */
function mustReplace(src: string, re: RegExp, file: string): string {
  if (!re.test(src)) {
    throw new Error(
      `applyApiVariants: expected GraphQL entry ${re} not found in apps/client/${file}`,
    );
  }
  return src.replace(re, '');
}

/** api=rest|both: the client stays on REST, so its config goes back to the pre-GraphQL shape. */
async function stripGraphqlClient(targetDir: string): Promise<void> {
  const client = join(targetDir, CLIENT);
  const deps = new Set(Object.keys(MANIFEST.apiClient.deps));
  await stripJsonKeys(join(client, 'package.json'), (k) => deps.has(k));

  const projectPath = join(client, 'project.json');
  const project = await readIfExists(projectPath);
  if (project !== null) {
    const parsed = JSON.parse(project) as { targets?: Record<string, unknown> };
    if (parsed.targets?.['graphql-codegen']) {
      delete parsed.targets['graphql-codegen'];
      await writeFile(projectPath, JSON.stringify(parsed, null, 2) + '\n');
    }
  }

  const vitePath = join(client, 'vite.config.mts');
  const vite = await readIfExists(vitePath);
  if (vite !== null) {
    let next = mustReplace(
      vite,
      /^import graphqlLoader from 'vite-plugin-graphql-loader';\n/m,
      'vite.config.mts',
    );
    next = mustReplace(next, /^[ \t]*graphqlLoader\(\),\n/m, 'vite.config.mts');
    await writeFile(vitePath, next);
  }

  for (const cfg of ['tsconfig.app.json', 'tsconfig.spec.json']) {
    const path = join(client, cfg);
    const src = await readIfExists(path);
    if (src !== null) await writeFile(path, mustReplace(src, /,\s*"graphql-loader\.d\.ts"/, cfg));
  }

  // Never leave a GraphQL twin behind (the copy already excludes them).
  for (const name of CLIENT_SWAPS) {
    await rm(join(client, 'src/queries', `${name}.gql-api.ts`), { force: true });
    await rm(join(client, 'src/queries/__tests__', `${name}.gql-api.unit.test.ts`), {
      force: true,
    });
  }
}

/**
 * Client half of the `--api` axis (spec section 8, decisions 5 and 10), after
 * selectClientTemplate promoted the template to apps/client:
 *  - graphql: the `*.gql-api.ts` query hooks (and their tests) replace the REST ones; pages
 *    import `queries/<name>` either way.
 *  - rest/both: the client stays on REST; strip the loader plugin, the `*.graphql` d.ts includes,
 *    the GraphQL client deps and the graphql-codegen target.
 */
export async function applyApiVariants(targetDir: string, opts: CreateIcoreOptions): Promise<void> {
  if (opts.ui === 'none' || !existsSync(join(targetDir, CLIENT))) return;
  if (opts.api === 'graphql') await swapClientQueries(targetDir);
  else await stripGraphqlClient(targetDir);
}
