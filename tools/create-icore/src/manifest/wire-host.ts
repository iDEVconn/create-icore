import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { hostOf, type CreateIcoreOptions } from '../lib/options.js';

/** Which hosted features this project has (mirrors what the generator keeps on disk). */
function features(opts: CreateIcoreOptions) {
  return {
    auth: opts.authProvider !== 'none',
    upload: opts.upload !== 'none',
    notes: opts.example === 'notes',
  };
}

/** `apps/worker/src/hosted-apps.ts`: the one file that names the gateway/microservice modules to host. */
export function renderHostedApps(opts: CreateIcoreOptions): string {
  const f = features(opts);
  const imports: string[] = [];
  const gateway: string[] = [];
  const services: string[] = [];
  if (f.auth) {
    imports.push(
      "import { AuthModule } from '../../api/src/app/auth/auth.module';",
      "import { AbilitiesModule } from '../../api/src/app/abilities/abilities.module';",
      "import { ProfileModule } from '../../api/src/app/profile/profile.module';",
      "import { AppModule as AuthMsModule } from '../../microservices/auth/src/app/app.module';",
    );
    gateway.push('AuthModule', 'AbilitiesModule', 'ProfileModule');
    services.push("{ prefix: 'AUTH', module: AuthMsModule }");
  }
  if (f.upload) {
    imports.push(
      "import { StorageModule } from '../../api/src/app/storage/storage.module';",
      "import { AppModule as UploadMsModule } from '../../microservices/upload/src/app/app.module';",
    );
    gateway.push('StorageModule');
    services.push("{ prefix: 'UPLOAD', module: UploadMsModule }");
  }
  if (f.notes) {
    imports.push(
      "import { NotesModule } from '../../api/src/app/notes/notes.module';",
      "import { AppModule as NotesMsModule } from '../../microservices/notes/src/app/app.module';",
    );
    gateway.push('NotesModule');
    services.push("{ prefix: 'NOTES', module: NotesMsModule }");
  }
  return `// The Worker hosts the gateway's and the microservices' own modules in one isolate. This is the ONLY
// file that imports another app's source. Generated by create-icore for the features you picked;
// edit it when you add or remove a microservice.
import type { Type } from '@nestjs/common';
${imports.join('\n')}

/** The gateway's feature modules (the Worker adds its own config, throttler and bindings). */
export const GATEWAY_FEATURE_MODULES: Type<unknown>[] = [${gateway.join(', ')}];

/**
 * \`AuthModule\` registers the global \`ThrottlerGuard\` next to the auth guards. A project without auth
 * has no \`AuthModule\`, so the Worker registers the guard itself (rate limiting never goes missing).
 */
export const FEATURES_REGISTER_THROTTLER_GUARD = ${f.auth};

/** The microservices started next to the gateway; \`<PREFIX>_TRANSPORT=local\` wires each to it. */
export const MICROSERVICES: { prefix: string; module: Type<unknown> }[] = [
  ${services.join(',\n  ')}
];
`;
}

/** wrangler `vars` (plain text, committed) for this project. */
export function workerVars(opts: CreateIcoreOptions): Record<string, string> {
  const f = features(opts);
  const vars: Record<string, string> = {};
  if (f.auth) vars['SESSION_STORE'] = 'durable-object';
  if (f.auth) vars['AUTH_TRANSPORT'] = 'local';
  if (f.upload) vars['UPLOAD_TRANSPORT'] = 'local';
  if (f.notes) vars['NOTES_TRANSPORT'] = 'local';
  // The SPA is served by the same Worker, so the app's own origin is also the client origin
  // (provider e-mail links, CORS). Replace with your real URL / custom domain before deploying.
  vars['CLIENT_ORIGIN'] = `https://${opts.projectName}.example.workers.dev`;
  if (opts.authProvider === 'supabase') vars['SUPABASE_URL'] = 'https://<project-ref>.supabase.co';
  if (opts.upload === 'r2') {
    vars['R2_ACCOUNT_ID'] = '<cloudflare account id>';
    vars['R2_BUCKET'] = 'uploads';
  }
  return vars;
}

/** Secrets the deployed Worker needs (`wrangler secret put <NAME>`), in the order a human sets them. */
export function workerSecrets(opts: CreateIcoreOptions): string[] {
  const secrets: string[] = [];
  if (opts.authProvider !== 'none') secrets.push('AUTH_TCP_SECRET');
  if (opts.authProvider === 'supabase')
    secrets.push('SUPABASE_ANON_KEY', 'SUPABASE_SERVICE_ROLE_KEY');
  if (opts.upload === 'r2') secrets.push('R2_ACCESS_KEY_ID', 'R2_SECRET_ACCESS_KEY');
  return secrets;
}

/** `.github/workflows/deploy-cloudflare.yml`: build the client + Worker and `wrangler deploy` on push to main. */
export function renderDeployWorkflow(opts: CreateIcoreOptions): string {
  const secrets = workerSecrets(opts);
  const token =
    opts.dbProvider === 'd1' ? 'Workers Scripts: Edit, D1: Edit' : 'Workers Scripts: Edit';
  const header = [
    '# Deploys the Worker (gateway + microservices + the built client as static assets) on every push to',
    '# main. One-time setup, none of which belongs in git:',
    `#   - repository secrets CLOUDFLARE_API_TOKEN (${token}) and CLOUDFLARE_ACCOUNT_ID`,
    ...(secrets.length
      ? [
          '#   - Worker secrets, set once from apps/worker with: npx wrangler secret put <NAME>',
          ...secrets.map((name) => `#       ${name}`),
        ]
      : []),
    '#   - real values instead of the placeholders in apps/worker/wrangler.jsonc',
    '# A deployed Worker runs with NODE_ENV=production, so the dev fakes are off: real credentials are required.',
  ].join('\n');
  return `name: Deploy to Cloudflare

${header}

on:
  push:
    branches: [main]
  workflow_dispatch:

concurrency:
  group: deploy-cloudflare
  cancel-in-progress: false

jobs:
  deploy:
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v5

      - uses: actions/setup-node@v5
        with:
          node-version-file: .nvmrc

      - name: Install dependencies
        run: |
          if [ -f yarn.lock ]; then
            corepack enable
            yarn install --immutable
          elif [ -f pnpm-lock.yaml ]; then
            corepack enable
            pnpm install --frozen-lockfile
          else
            npm ci
          fi

      # Builds the client first (the Worker serves it as static assets), then compiles the Worker.
      - name: Build client + Worker
        run: npx nx run worker:build

      - name: Deploy
        working-directory: apps/worker
        run: npx wrangler deploy
        env:
          CLOUDFLARE_API_TOKEN: \${{ secrets.CLOUDFLARE_API_TOKEN }}
          CLOUDFLARE_ACCOUNT_ID: \${{ secrets.CLOUDFLARE_ACCOUNT_ID }}
`;
}

function renderDevVars(opts: CreateIcoreOptions): string {
  const lines = [
    '# Local development secrets for `wrangler dev` (copy to .dev.vars, which is git-ignored).',
    '# On a deployed Worker set them with `wrangler secret put <NAME>` instead.',
    "# Generate AUTH_TCP_SECRET with: node -e \"console.log(require('crypto').randomBytes(32).toString('hex'))\"",
  ];
  for (const name of workerSecrets(opts)) lines.push(`${name}=`);
  return `${lines.join('\n')}\n`;
}

/**
 * Specialises the generic `apps/worker` for the chosen features: the hosted module lists, the
 * wrangler vars and D1 binding, the local secrets template, the dev port the client proxies to
 * and the root `dev` script. A no-op for the Node host.
 */
export async function writeHostWiring(targetDir: string, opts: CreateIcoreOptions): Promise<void> {
  if (hostOf(opts) !== 'cloudflare') return;
  const worker = join(targetDir, 'apps/worker');

  await writeFile(join(worker, 'src/hosted-apps.ts'), renderHostedApps(opts));
  await writeFile(join(worker, '.dev.vars.example'), renderDevVars(opts));

  const wranglerPath = join(worker, 'wrangler.jsonc');
  let wrangler = await readFile(wranglerPath, 'utf8');
  const vars = Object.entries(workerVars(opts))
    .map(([k, v]) => `    ${JSON.stringify(k)}: ${JSON.stringify(v)},`)
    .join('\n');
  wrangler = wrangler.replace(/"vars": \{[\s\S]*?\n {2}\},\n/, `"vars": {\n${vars}\n  },\n`);
  if (opts.dbProvider === 'd1' && opts.example === 'notes') {
    wrangler = wrangler.replace(
      /\n {2}"vars": /,
      `\n  // Create it with \`wrangler d1 create ${opts.projectName}\` and paste the id here.\n  "d1_databases": [\n    { "binding": "DB", "database_name": "${opts.projectName}", "database_id": "<d1 database id>" },\n  ],\n  "vars": `,
    );
  }
  // The built client is served by the Worker itself: `/api/*` runs the Worker first, every other
  // path is a static asset or falls back to the SPA's index.html.
  wrangler = wrangler.replace(
    /\n {2}"durable_objects"/,
    `\n  "assets": {\n    "directory": "../../dist/apps/client",\n    "not_found_handling": "single-page-application",\n    "run_worker_first": ["/api/*"],\n  },\n  "durable_objects"`,
  );
  wrangler = wrangler.replace(/"name": "icore"/, `"name": ${JSON.stringify(opts.projectName)}`);
  await writeFile(wranglerPath, wrangler);

  // The client dev server proxies /api to :3001; the Worker takes that port in development.
  const projectPath = join(worker, 'project.json');
  const project = await readFile(projectPath, 'utf8');
  await writeFile(
    projectPath,
    project
      .replace('wrangler dev --local', 'wrangler dev --local --port 3001')
      // The client must be built before the Worker bundles it as static assets.
      .replace('"dependsOn": []', '"dependsOn": ["client:vite:build"]'),
  );

  await mkdir(join(targetDir, '.github/workflows'), { recursive: true });
  await writeFile(
    join(targetDir, '.github/workflows/deploy-cloudflare.yml'),
    renderDeployWorkflow(opts),
  );

  const pkgPath = join(targetDir, 'package.json');
  const pkg = JSON.parse(await readFile(pkgPath, 'utf8')) as { scripts: Record<string, string> };
  pkg.scripts['dev'] =
    'NX_DAEMON=false NX_ISOLATE_PLUGINS=false nx run-many -t serve -p worker client';
  await writeFile(pkgPath, `${JSON.stringify(pkg, null, 2)}\n`);
}
